	/** Пересчитать язык (при смене настройки и периодически для режима «Авто»). */
	public static void refresh() {
		String l = SkinStore.language();
		if (l.equals("ru")) english = false;
		else if (l.equals("en")) english = true;
		else {
			boolean ru = false;
			try {
				String sel = Minecraft.getInstance().getLanguageManager().getSelected();
				ru = sel != null && sel.toLowerCase().startsWith("ru");
			} catch (Throwable ignored) {
			}
			english = !ru;
		}
	}

	public static boolean isEnglish() {
		return english;
	}

	public static String t(String ru) {
		if (!english || ru == null) return ru;
		String e = EN.get(ru);
		return e != null ? e : ru;
	}

